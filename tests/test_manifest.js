const assert = require('assert');
const fs = require('fs');
const current = require('../package.json');
const upstream = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const a = current.contributes, b = upstream.contributes;
assert.strictEqual(`${current.publisher}.${current.name}`, 'cuviss.soloas');
assert.strictEqual(current.version, '0.2.0');
assert.strictEqual(a.configurationDefaults['files.associations']['*.as'], 'soloas-angelscript');
assert.ok(a.languages.some(x => x.id === 'soloas-angelscript'));
const language = a.languages.find(x => x.id === 'soloas-angelscript');
assert.strictEqual(language.aliases[0], 'soloAS AngelScript');
assert.ok(language.extensions.includes('.as'));
assert.ok(a.languages.every(x => x.aliases.every(alias => !b.languages.flatMap(y => y.aliases || []).includes(alias))));
assert.ok(a.debuggers.some(x => x.type === 'soloas' && x.initialConfigurations.every(c => c.type === 'soloas') && x.configurationSnippets.every(c => c.body.type === 'soloas')));
const disjoint = (ours, theirs) => assert.ok(ours.every(x => !theirs.includes(x)), `${ours} intersects ${theirs}`);
disjoint(a.languages.map(x => x.id), b.languages.map(x => x.id));
disjoint(a.debuggers.map(x => x.type), b.debuggers.map(x => x.type));
disjoint(a.commands.map(x => x.command), b.commands.map(x => x.command));
disjoint(a.viewsContainers.activitybar.map(x => x.id), b.viewsContainers.activitybar.map(x => x.id));
disjoint(Object.values(a.views).flat().map(x => x.id), Object.values(b.views).flat().map(x => x.id));
disjoint(a.grammars.map(x => x.scopeName), b.grammars.map(x => x.scopeName));
const client = fs.readFileSync('extension/src/extension.ts', 'utf8');
assert.ok(client.includes("language: 'soloas-angelscript'"));
assert.ok(client.includes("registerDebugConfigurationProvider('soloas'"));
assert.ok(client.includes("getExtension('Hazelight.unreal-angelscript')"));
assert.ok(client.includes("globalState.get<boolean>('upstreamNoticeShown')"));
assert.ok(client.includes("globalState.update('upstreamNoticeShown', true)"));
assert.ok(client.includes("executeCommand('extension.open', 'Hazelight.unreal-angelscript')"));
assert.ok(client.includes('Open Hazelight Extension to Disable'));
assert.ok(fs.readFileSync('README.md', 'utf8').includes('duplicate diagnostics'));
for (const grammar of a.grammars) assert.strictEqual(JSON.parse(fs.readFileSync(grammar.path)).scopeName, grammar.scopeName);
console.log('Extension identity and coexistence declarations: passed');
